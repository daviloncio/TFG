def tratamiento_zona_tarifaria(df):
    """H2: mantiene id_tipo_titulo (código) y añade zonas_permitidas (array de zonas)"""
    from pyspark.sql import functions as F

    TODAS_LISTA = ['A','B1','B2','B3','C1','C2','E1','E2']
    corr = {int(k): (TODAS_LISTA if v == TODAS else v) for k, v in correspondencias.items()}

    m = F.create_map(*[
        x
        for k, zonas in corr.items()
        for x in (F.lit(k), F.array(*[F.lit(z) for z in zonas]))
    ])

    df = df.withColumn("id_tipo_titulo", F.trim(F.col("id_tipo_titulo")).cast("int"))

    df = df.withColumn(
        "zonas_permitidas",
        F.element_at(m, F.col("id_tipo_titulo"))
    )

    return df

    

    
    